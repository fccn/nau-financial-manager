    def test_export_refuses_a_product_id_with_control_characters(self):
        """
        Should not export with a product id having line breaks, it would be used in a header of the response.
        """
        for product_id in ["a\nb", "a\r\nb", "a\x00b", "a\tb"]:
            response = self.export(product_id=product_id)

            self.assertEqual(response.status_code, 200)
            self.assertNotIn("Content-Disposition", response)
            self.assertEqual(list(response.context["form"].errors.keys()), ["product_id"])
            self.assertIn(
                "The product id can not have line breaks or other control characters.",
                response.context["form"].errors["product_id"],
            )

    def test_export_does_not_write_formulas_neither_links(self):
        """
        Should write the texts as they are, never as formulas or links, the texts might come from outside.
        """
        descriptions = ["=1+1", "https://example.com/", "+1", "@SUM(A1)"]
        for item, description in zip(self.items[1:] + self.other_items, descriptions):
            TransactionItem.objects.filter(id=item.id).update(description=description)

        content = self.get_content(self.export())

        results, _ = read_xlsx(content)
        self.assertCountEqual([result["product_name"] for result in results], descriptions)
        with zipfile.ZipFile(BytesIO(content)) as xlsx:
            for name in xlsx.namelist():
                self.assertNotIn("hyperlink", name)
                if name.startswith("xl/worksheets/"):
                    sheet = xlsx.read(name)
                    self.assertNotIn(b"<f>", sheet)
                    self.assertNotIn(b"<hyperlink", sheet)

