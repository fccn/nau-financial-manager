XLSX_CONTENT_TYPE = "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet"
XLSX_NAMESPACE = {"m": "http://schemas.openxmlformats.org/spreadsheetml/2006/main"}

RESULT_COLUMNS = [
    "transaction_id",
    "transaction_date",
    "product_name",
    "product_id",
    "organization",
    "total_amount_including_vat",
    "total_amount_exclude_vat",
    "percentage_for_organization",
    "amount_for_organization_including_vat",
    "amount_for_organization_exclude_vat",
    "percentage_for_nau",
    "amount_for_nau_including_vat",
    "amount_for_nau_exclude_vat",
    "discount_rate",
]
CONFIGURATION_COLUMNS = ["id", "organization", "product_id", "partner_percentage", "start_date", "end_date"]


def read_xlsx(content: bytes) -> list[list[dict]]:
    """
    Reads a xlsx file and returns its sheets, each sheet is a list of rows
    and each row is a dict having the header of the sheet as keys.
    """

    def read_cell(cell, strings: list[str]):
        value = cell.find("m:v", XLSX_NAMESPACE).text
        return strings[int(value)] if cell.get("t") == "s" else float(value)

    with zipfile.ZipFile(BytesIO(content)) as xlsx:
        strings = [
            "".join(string.itertext())
            for string in ElementTree.fromstring(xlsx.read("xl/sharedStrings.xml")).findall(  # nosec B314
                "m:si", XLSX_NAMESPACE
            )
        ]
        sheets = []
        for name in sorted(name for name in xlsx.namelist() if name.startswith("xl/worksheets/sheet")):
            rows = []
            for row in ElementTree.fromstring(xlsx.read(name)).iterfind(".//m:row", XLSX_NAMESPACE):  # nosec B314
                rows.append(
                    {
                        re.sub(r"\d", "", cell.get("r")): read_cell(cell, strings)
                        for cell in row.findall("m:c", XLSX_NAMESPACE)
                    }
                )
            header, *values = rows
            sheets.append([{column: row.get(letter) for letter, column in header.items()} for row in values])

    return sheets


class SplitExportBaseTestCase(TestCase):
    """
    Defines the data shared by the tests of all the ways of exporting the split revenue report.

    - 2 organizations with a revenue configuration, without a period, giving 70% to the partner
    - 3 transactions of the first organization, one of them 40 days old
    - 2 transactions of the second organization
    - 1 transaction of an organization without revenue configuration, it never gets in the report
    - 1 transaction without items, it never gets in the report
    """

    partner_percentage = Decimal("0.70")
    nau_percentage = Decimal("0.30")

    def setUp(self) -> None:
        self.today = timezone.localdate()
        self.organization = OrganizationFactory.create()
        self.other_organization = OrganizationFactory.create()

        self.items: list[TransactionItem] = [
            self.create_item(organization_code=self.organization.short_name) for _ in range(3)
        ]
        self.other_items: list[TransactionItem] = [
            self.create_item(organization_code=self.other_organization.short_name) for _ in range(2)
        ]
        self.old_item = self.items[0]
        self.old_date = timezone.now() - timedelta(days=40)
        Transaction.objects.filter(id=self.old_item.transaction.id).update(transaction_date=self.old_date)
        self.item_without_configuration = self.create_item(organization_code="NOCONFIG")
        self.transaction_without_items = TransactionFactory.create()

        self.product_id = self.items[0].product_id
        self.other_product_id = self.other_items[0].product_id
        for organization, product_id in [
            (self.organization, self.product_id),
            (self.other_organization, self.other_product_id),
        ]:
            RevenueConfigurationFactory.create(
                organization=organization,
                product_id=product_id,
                partner_percentage=self.partner_percentage,
                start_date=None,
                end_date=None,
            )

    def create_item(self, organization_code: str, **kwargs) -> TransactionItem:
        item = TransactionItemFactory.create(
            transaction=TransactionFactory.create(),
            organization_code=organization_code,
            **kwargs,
        )
        item.refresh_from_db()

        return item

    def assert_report(self, content: bytes, items: list[TransactionItem]) -> None:
        """
        Validates that the xlsx report has exactly the given transaction items, each one
        with the expected split values, and the revenue configurations used to calculate them.
        """
        results, configurations = read_xlsx(content)

        self.assertEqual(len(results), len(items))
        results_per_transaction = {result["transaction_id"]: result for result in results}
        for item in items:
            result = results_per_transaction[item.transaction.transaction_id]
            self.assertEqual(list(result.keys()), RESULT_COLUMNS)
            self.assertEqual(result["product_name"], item.description)
            self.assertEqual(result["product_id"], item.product_id)
            self.assertEqual(result["organization"], item.organization_code)
            for column, expected in {
                "total_amount_including_vat": item.transaction.total_amount_include_vat,
                "total_amount_exclude_vat": item.transaction.total_amount_exclude_vat,
                "percentage_for_organization": self.partner_percentage,
                "amount_for_organization_including_vat": item.price_incl_vat * self.partner_percentage,
                "amount_for_organization_exclude_vat": item.price_excl_vat * self.partner_percentage,
                "percentage_for_nau": self.nau_percentage,
                "amount_for_nau_including_vat": item.price_incl_vat * self.nau_percentage,
                "amount_for_nau_exclude_vat": item.price_excl_vat * self.nau_percentage,
                "discount_rate": item.discount_rate,
            }.items():
                self.assertAlmostEqual(result[column], float(expected), places=6, msg=column)

        expected_configurations = {(item.organization_code, item.product_id) for item in items}
        self.assertEqual(
            {(configuration["organization"], configuration["product_id"]) for configuration in configurations},
            expected_configurations,
        )
        for configuration in configurations:
            self.assertEqual(list(configuration.keys()), CONFIGURATION_COLUMNS)
            self.assertEqual(configuration["partner_percentage"], "0.70")


class ExportSplitRevenueAdminTestCase(SplitExportBaseTestCase):
    """
    Tests the page of the admin used to download the split revenue report.
    """

    def setUp(self) -> None:
        super().setUp()
        self.url = reverse("admin:shared_revenue_revenueconfiguration_export_split_revenue")
        self.changelist_url = reverse("admin:shared_revenue_revenueconfiguration_changelist")
        self.user = self.create_user("exporter", permissions=["view_revenueconfiguration", "export_split_revenue"])
        self.client.force_login(self.user)

    def create_user(self, username: str, permissions: tuple[str, ...] = (), is_staff: bool = True):
        user = get_user_model().objects.create_user(
            username=username,
            email=f"{username}@example.com",
            password="password",  # nosec B106
            is_staff=is_staff,
        )
        user.user_permissions.set(Permission.objects.filter(codename__in=permissions))

        return user

    def export(self, **data):
        data = {"start_date": self.today.isoformat(), "end_date": self.today.isoformat(), **data}

        return self.client.post(self.url, data)

    def get_content(self, response) -> bytes:
        return b"".join(response.streaming_content)

    def assert_is_report(self, response, file_name_prefix: str = "report_split_revenue_") -> None:
        self.assertEqual(response.status_code, 200)
        self.assertEqual(response["Content-Type"], XLSX_CONTENT_TYPE)
        self.assertRegex(
            response["Content-Disposition"],
            rf'^attachment; filename="{re.escape(file_name_prefix)}\d{{14}}_[A-Za-z0-9]{{10}}\.xlsx"$',
        )

    def test_anonymous_user_is_redirected_to_login(self):
        """
        Should not be possible to reach the export page without being logged in.
        """
        self.client.logout()

        for response in [self.client.get(self.url), self.export()]:
            self.assertRedirects(response, f"{reverse('admin:login')}?next={self.url}")

    def test_non_staff_user_is_redirected_to_login(self):
        """
        Should not be possible to reach the export page for a non staff user, even having the permission.
        """
        self.client.force_login(self.create_user("non_staff", permissions=["export_split_revenue"], is_staff=False))

        for response in [self.client.get(self.url), self.export()]:
            self.assertRedirects(response, f"{reverse('admin:login')}?next={self.url}")

    def test_staff_user_without_permission_is_forbidden(self):
        """
        Should not be possible to see the form neither to export the report without the export permission.
        """
        self.client.force_login(self.create_user("viewer", permissions=["view_revenueconfiguration"]))

        for response in [self.client.get(self.url), self.export()]:
            self.assertEqual(response.status_code, 403)

