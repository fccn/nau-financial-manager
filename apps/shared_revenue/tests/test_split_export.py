    def test_export_with_several_products_of_the_same_organization(self):
        """
        Should split each transaction only once, using the revenue configuration of its own product,
        when an organization has revenue configurations for more than one product.
        """
        half_product_id = "course-v1:HALF+PRODUCT+2024_T1"
        half_percentage = Decimal("0.50")
        half_item = self.create_item(organization_code=self.organization.short_name, product_id=half_product_id)
        RevenueConfigurationFactory.create(
            organization=self.organization,
            product_id=half_product_id,
            partner_percentage=half_percentage,
            start_date=None,
            end_date=None,
        )

        def assert_half_result(result: dict) -> None:
            self.assertEqual(result["transaction_id"], half_item.transaction.transaction_id)
            self.assertEqual(result["product_id"], half_product_id)
            for column, expected in {
                "percentage_for_organization": half_percentage,
                "amount_for_organization_including_vat": half_item.price_incl_vat * half_percentage,
                "amount_for_organization_exclude_vat": half_item.price_excl_vat * half_percentage,
                "percentage_for_nau": half_percentage,
                "amount_for_nau_including_vat": half_item.price_incl_vat * half_percentage,
                "amount_for_nau_exclude_vat": half_item.price_excl_vat * half_percentage,
            }.items():
                self.assertAlmostEqual(result[column], float(expected), places=6, msg=column)

        results, configurations = read_xlsx(self.get_content(self.export()))
        self.assertCountEqual(
            [result["transaction_id"] for result in results],
            [item.transaction.transaction_id for item in [*self.items[1:], *self.other_items, half_item]],
        )
        self.assertEqual(len(configurations), 3)
        for result in results:
            if result["product_id"] == half_product_id:
                assert_half_result(result)
            else:
                self.assertAlmostEqual(result["percentage_for_organization"], float(self.partner_percentage))
                self.assertAlmostEqual(result["percentage_for_nau"], float(self.nau_percentage))

        response = self.export(product_id=self.product_id)
        self.assert_report(self.get_content(response), items=self.items[1:])

        results, configurations = read_xlsx(self.get_content(self.export(product_id=half_product_id)))
        self.assertEqual(len(results), 1)
        assert_half_result(results[0])
        self.assertEqual([configuration["product_id"] for configuration in configurations], [half_product_id])

